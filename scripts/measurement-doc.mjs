#!/usr/bin/env node
// Writes docs/MEASUREMENT.md from src/lib/measure/registry.ts.
// --check writes nothing and exits 1 when the document differs; `audit` runs
// the same comparison. It reads files only: the audit job has no TypeScript.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import vm from "node:vm";

export const REGISTRY = "src/lib/measure/registry.ts";
export const MEASUREMENT_DOC = "docs/MEASUREMENT.md";
const CONSTANTS = "src/lib/config/constants.ts";

const read = (root, rel) => readFileSync(path.join(root, rel), "utf8");

/** A literal constant's value: a string, a number, or a template whose
 *  `${NAME}` parts are constants of the same files. */
export function readConstant(root, name, files = [CONSTANTS]) {
  for (const rel of files) {
    const m = read(root, rel).match(new RegExp(`export const ${name}\\b[^=]*=\\s*([^;\\n]+)`));
    if (m === null) continue;
    const raw = m[1].replace(/\s+as const$/, "").trim();
    if (/^-?\d+(\.\d+)?$/.test(raw)) return raw;
    const quoted = raw.match(/^"([^"]*)"$/);
    if (quoted) return quoted[1];
    const template = raw.match(/^`([^`]*)`$/);
    if (template) return template[1].replace(/\$\{(\w+)\}/g, (_, inner) => readConstant(root, inner, files));
    throw new Error(`${rel}: ${name} is not a literal (${raw})`);
  }
  throw new Error(`no constant ${name} in ${files.join(", ")}`);
}

/** The registry's list, evaluated from the text between its markers. */
export function readMeasures(root) {
  const text = read(root, REGISTRY);
  const m = text.match(/\/\/ measures:begin\n([\s\S]*?)\n\s*\/\/ measures:end/);
  if (m === null) throw new Error(`${REGISTRY}: no measures:begin / measures:end markers`);
  return vm.runInNewContext(`(${m[1]})`, Object.create(null), { timeout: 1000 });
}

/** Every reason the registry cannot be published. */
export function measureProblems(root, measures) {
  const problems = [];
  const ids = new Set();
  const keys = new Set();
  for (const measure of measures) {
    const at = measure.id ?? "(no id)";
    for (const field of ["id", "definition", "source", "cadence"]) {
      if (typeof measure[field] !== "string" || measure[field].trim() === "") problems.push(`${at}: no ${field}`);
    }
    if (!["tile", "mail"].includes(measure.shown?.on) || typeof measure.shown?.key !== "string") problems.push(`${at}: shown needs on and key`);
    if (ids.has(measure.id)) problems.push(`${at}: id listed twice`);
    if (keys.has(measure.shown?.key)) problems.push(`${at}: ${measure.shown?.key} is shown by two measures`);
    ids.add(measure.id);
    keys.add(measure.shown?.key);
    const [file, name] = String(measure.source).split("#");
    if (!existsSync(path.join(root, file))) problems.push(`${at}: source ${file} does not exist`);
    else if (!new RegExp(`\\b(function|const)\\s+${name}\\b`).test(read(root, file))) problems.push(`${at}: ${file} declares no ${name}`);
  }
  return problems;
}

const cell = (s) => s.replace(/\|/g, "\\|");

export function measurementDoc(root) {
  const measures = readMeasures(root);
  const problems = measureProblems(root, measures);
  if (problems.length) throw new Error(problems.join("\n"));
  const words = (s) => s.replace(/\{(\w+)\}/g, (_, name) => readConstant(root, name));
  const section = (on, title) => [
    `## ${title}`,
    "",
    "| Id | Shown as | Definition | Source | Cadence |",
    "|---|---|---|---|---|",
    ...measures
      .filter((m) => m.shown.on === on)
      .map((m) => `| ${m.id} | \`${m.shown.key}\` | ${cell(words(m.definition))} | \`${cell(m.source)}\` | ${cell(m.cadence)} |`),
    "",
  ];
  return [
    "# Measurement",
    "",
    `Generated by \`node scripts/measurement-doc.mjs\` from \`${REGISTRY}\`. Do not edit it here: change the registry and run the script. \`audit\` fails when this file and the registry differ.`,
    "",
    "A number nobody measured is never shown as 0: each definition says what is shown instead.",
    "",
    ...section("tile", "Overview tiles"),
    ...section("mail", "Monday mail"),
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const doc = measurementDoc(root);
  const target = path.join(root, MEASUREMENT_DOC);
  if (process.argv.includes("--check")) {
    const same = existsSync(target) && readFileSync(target, "utf8") === doc;
    console.log(same ? `${MEASUREMENT_DOC} matches the registry` : `${MEASUREMENT_DOC} differs: run node scripts/measurement-doc.mjs`);
    process.exit(same ? 0 : 1);
  }
  writeFileSync(target, doc);
  console.log(`wrote ${MEASUREMENT_DOC}`);
}
