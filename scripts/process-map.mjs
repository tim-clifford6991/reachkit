#!/usr/bin/env node
// Writes docs/PROCESSES.md from the job registry: src/jobs/index.ts's `jobs`,
// each definition's trigger and key, and the comment on its id in
// src/jobs/types.ts. --check writes nothing and exits 1 when the document
// differs; `audit` runs the same comparison. It reads files only, and a
// definition it cannot read fails rather than being left out.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { readConstant } from "./measurement-doc.mjs";

export const PROCESS_DOC = "docs/PROCESSES.md";
const INDEX = "src/jobs/index.ts";
const TYPES = "src/jobs/types.ts";
const CONSTANTS = "src/lib/config/constants.ts";

const read = (root, rel) => readFileSync(path.join(root, rel), "utf8");

/** What each id is for: the comment beside it in the `JobId` union. */
function purposes(root) {
  const types = read(root, TYPES);
  const at = types.indexOf("export type JobId =");
  if (at < 0) throw new Error(`${TYPES}: no JobId union`);
  const text = types.slice(at, types.indexOf("\n\n", at));
  return new Map([...text.matchAll(/\|\s*"([^"]+)"[;\s]*\/\/\s*([^\n]+)/g)].map((m) => [m[1], m[2].trim()]));
}

/** One definition, read out of its own file. */
function definition(root, name, file) {
  const text = read(root, file);
  const start = text.search(new RegExp(`export const ${name}: JobDefinition = \\{`));
  if (start < 0) throw new Error(`${file}: no JobDefinition ${name}`);
  const body = text.slice(start, text.indexOf("\n};", start));
  const id = body.match(/\n\s+id: "([^"]+)"/)?.[1];
  const trigger = body.match(/\n\s+trigger: \{([^}]*)\}/)?.[1];
  const key = body.match(/\n\s+idempotencyKey: \[([^\]]*)\]/)?.[1];
  if (id === undefined || trigger === undefined || key === undefined) throw new Error(`${file}: cannot read ${name}'s id, trigger or idempotencyKey`);
  const value = (raw) => {
    const literal = raw.trim().match(/^"([^"]*)"$/);
    return literal ? literal[1] : readConstant(root, raw.trim(), [file, CONSTANTS]);
  };
  const field = (f) => trigger.match(new RegExp(`\\b${f}:\\s*([^,]+)`))?.[1];
  const kind = value(field("kind") ?? "");
  let when;
  if (kind === "cron") when = `cron \`${value(field("cron"))}\``;
  else if (kind === "event") {
    const after = field("afterHours");
    when = `event \`${value(field("event"))}\`${after === undefined ? "" : `, ${value(after)} h later`}`;
  } else throw new Error(`${file}: ${name}'s trigger kind is not event or cron`);
  const fields = [...key.matchAll(/"([^"]+)"/g)].map((m) => `\`${m[1]}\``);
  return { id, file, when, perSubject: /\n\s+perSubject[:,]/.test(body), key: fields };
}

export function readJobs(root) {
  const index = read(root, INDEX);
  const files = new Map(
    [...index.matchAll(/import \{ (\w+) \} from "\.\/([\w-]+)";/g)].map((m) => [m[1], `src/jobs/${m[2]}.ts`])
  );
  const list = index.match(/export const jobs: readonly JobDefinition\[\] = Object\.freeze\(\[([\s\S]*?)\]\)/);
  if (list === null) throw new Error(`${INDEX}: no jobs list`);
  const names = list[1].split(",").map((s) => s.trim()).filter(Boolean);
  return names.map((name) => {
    const file = files.get(name);
    if (file === undefined || !existsSync(path.join(root, file))) throw new Error(`${INDEX}: ${name} is not imported from a job file`);
    return definition(root, name, file);
  });
}

const cell = (s) => s.replace(/\|/g, "\\|");

export function processMap(root) {
  const jobs = readJobs(root);
  const why = purposes(root);
  const missing = jobs.filter((job) => !why.has(job.id)).map((job) => job.id);
  if (missing.length) throw new Error(`${TYPES}: no comment on ${missing.join(", ")}`);
  return [
    "# Processes",
    "",
    `Generated by \`node scripts/process-map.mjs\` from \`${INDEX}\` and \`${TYPES}\`. Do not edit it here: change the job registry and run the script. \`audit\` fails when this file and the registry differ.`,
    "",
    "Every background process is one of these jobs. A clock tick that finds nothing due records that it skipped; the kill switch stops a job before any spend.",
    "",
    "| Job | Starts on | Runs | Deduplicated by | What it does | Defined in |",
    "|---|---|---|---|---|---|",
    ...jobs.map((job) =>
      [
        "",
        `\`${job.id}\``,
        job.when,
        job.perSubject ? "one run per subject" : "one run",
        job.key.length ? job.key.join(", ") : "the engine's own database constraint",
        cell(why.get(job.id)),
        `\`${job.file}\``,
        "",
      ].join(" | ").trim()
    ),
    "",
  ].join("\n");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const doc = processMap(root);
  const target = path.join(root, PROCESS_DOC);
  if (process.argv.includes("--check")) {
    const same = existsSync(target) && readFileSync(target, "utf8") === doc;
    console.log(same ? `${PROCESS_DOC} matches the job registry` : `${PROCESS_DOC} differs: run node scripts/process-map.mjs`);
    process.exit(same ? 0 : 1);
  }
  writeFileSync(target, doc);
  console.log(`wrote ${PROCESS_DOC}`);
}
